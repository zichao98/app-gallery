// Bundles the built front end (dist/) into the Worker as a module, so a deploy
// is a single script upload with no separate static-asset upload step.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".webmanifest": "application/manifest+json",
};
const TEXT = new Set([".html", ".js", ".css", ".svg", ".webmanifest"]);

function walk(dir) {
  return readdirSync(dir).flatMap(f => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = {};
for (const p of walk("dist")) {
  const ext = extname(p);
  if (!TYPES[ext]) continue;
  const path = "/" + relative("dist", p).split("\\").join("/");
  files[path] = TEXT.has(ext)
    ? { type: TYPES[ext], body: readFileSync(p, "utf8") }
    : { type: TYPES[ext], body: readFileSync(p).toString("base64"), base64: true };
}

writeFileSync(
  "worker/static.gen.ts",
  `// Generated by scripts/embed.mjs — do not edit.\nexport const FILES: Record<string, { type: string; body: string; base64?: boolean }> = ${JSON.stringify(files)};\n`,
);
console.log(`embedded ${Object.keys(files).length} files`);
